#!/usr/bin/env python3
"""Single source of truth for UI strings. Run `python3 tools/gen_strings.py` after editing
tools/strings.tsv; it rewrites app/src/main/res/values{,-hi,-mr}/strings.xml so the three
languages can never drift apart. Format per line: key<TAB>en<TAB>hi<TAB>mr"""
import os, sys, html

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = []
for n, line in enumerate(open(os.path.join(root, "tools", "strings.tsv"), encoding="utf-8"), 1):
    line = line.rstrip("\n")
    if not line or line.startswith("#"):
        continue
    parts = line.split("\t")
    if len(parts) != 4 or any(not p.strip() for p in parts):
        sys.exit(f"strings.tsv line {n}: need key, en, hi, mr (tab separated, non-empty)")
    rows.append(parts)
keys = [r[0] for r in rows]
dupes = {k for k in keys if keys.count(k) > 1}
if dupes:
    sys.exit(f"duplicate keys: {sorted(dupes)}")

def esc(s):
    s = s.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("'", "\\'").replace('"', '\\"')
    return s.replace("\\\\n", "\\n")

for col, folder in ((1, "values"), (2, "values-hi"), (3, "values-mr")):
    path = os.path.join(root, "app", "src", "main", "res", folder, "strings.xml")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- GENERATED by tools/gen_strings.py from tools/strings.tsv. Do not edit by hand. -->\n<resources>\n')
        for r in rows:
            f.write(f'    <string name="{r[0]}">{esc(r[col])}</string>\n')
        f.write("</resources>\n")
print(f"wrote {len(rows)} strings x 3 languages")
